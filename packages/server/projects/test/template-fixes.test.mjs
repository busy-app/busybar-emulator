// What create puts right in a project of the official template (template-fixes.mjs): the settings helper that reads
// nothing on the released firmware, and the AGENTS.md that sends an agent to npm and a bar on USB.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";

import { loadCommands, parseArguments } from "../../cli/busy-emulator.mjs";
import { checkSettingsSchema } from "../settings-schema.mjs";
import { agentsSection, fixSettingsHelper, fixTemplate, SECTION_BEGIN, SECTION_END, SETTINGS_HELPER, writeAgentsSection } from "../template-fixes.mjs";

// The template's own files (@busy-app/create-app 0.5.0), the parts that matter here.
const TEMPLATE_HELPER = `// Settings values, read through the global the JerryScript runtime provides.
export type SettingsValues = Record<string, unknown>;
interface SettingsApi { load(): Promise<SettingsValues>; save(values: SettingsValues): Promise<void>; }
function api(): SettingsApi | undefined {
  return (globalThis as { Settings?: SettingsApi }).Settings;
}
export async function loadValues(): Promise<SettingsValues | null> { return (await api()?.load()) ?? null; }
export async function saveValues(values: SettingsValues): Promise<void> { await api()?.save(values); }
`;
const TEMPLATE_AGENTS = `# AGENTS.md

Instructions for AI coding agents working on \`My App\`.

## Display, input and settings

- Settings are described in \`src/appmeta/settings.json\`. Read them with \`loadValues()\` from \`@shared/settings\` and fall back to the defaults in code when it returns \`null\`; persist with \`saveValues()\`. Do not put secrets in settings files.

## Code rules

- TypeScript is strict when the app is written in \`.ts\`; run \`npm run typecheck\`.
- Never edit \`dist/\`; it is generated by \`npm run build\`.

## Before finishing

Run \`npm run typecheck\` and \`npm run build\`, then check:
`;

function project(t, { typecheck = true, agents = TEMPLATE_AGENTS, helper = TEMPLATE_HELPER } = {}) {
  const dir = realpathSync(mkdtempSync(path.join(os.tmpdir(), "busy-template-")));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  mkdirSync(path.join(dir, "shared"));
  writeFileSync(path.join(dir, "package.json"), JSON.stringify({ name: "x", scripts: typecheck ? { typecheck: "tsc", build: "busy-cli build" } : { build: "busy-cli build" } }));
  if (helper !== null) writeFileSync(path.join(dir, "shared", "settings.ts"), helper);
  if (agents !== null) writeFileSync(path.join(dir, "AGENTS.md"), agents);
  writeFileSync(path.join(dir, "README.md"), "## Settings\n\n`loadValues()` returns `null` when nothing is stored yet — use the defaults.\n");
  return dir;
}
const read = (dir, name) => readFileSync(path.join(dir, name), "utf8");

test("the template's settings helper is replaced by one with the same names that asks the BUSY Bar's API", (t) => {
  const dir = project(t);
  assert.equal(fixSettingsHelper(dir), "replaced");
  const helper = read(dir, "shared/settings.ts");
  assert.equal(helper, SETTINGS_HELPER);
  for (const name of ["export type SettingsValues", "export async function loadValues(): Promise<SettingsValues | null>", "export async function saveValues("]) assert.ok(helper.includes(name), name);
  assert.match(helper, /device\.AppsSettingsGet\(\{ app_id: manifest\.id \}\)/);
  assert.doesNotMatch(helper, /globalThis/);
  // Once more: it is not the template's any more, and is left as it is.
  assert.equal(fixSettingsHelper(dir), "not-needed");
});

test("a helper that is not the template's broken one (a later template, the author's own) is left alone", (t) => {
  const own = "export async function loadValues() { return { mine: true }; }\n";
  const dir = project(t, { helper: own });
  assert.equal(fixSettingsHelper(dir), "not-needed");
  assert.equal(read(dir, "shared/settings.ts"), own);
  assert.equal(fixSettingsHelper(project(t, { helper: null })), "missing");
});

test("AGENTS.md gets the emulator's section before the template's first heading, once", (t) => {
  const dir = project(t);
  assert.equal(writeAgentsSection(dir), "added");
  const text = read(dir, "AGENTS.md");
  assert.ok(text.indexOf(SECTION_BEGIN) > text.indexOf("Instructions for AI coding agents"));
  assert.ok(text.indexOf(SECTION_END) < text.indexOf("## Display, input and settings"));
  assert.equal(text.split(SECTION_BEGIN).length, 2);
  assert.equal(writeAgentsSection(dir), "present");
  assert.equal(read(dir, "AGENTS.md"), text, "a second create's pass changes nothing");
});

test("the template's lines about npm run and the dead helper are rewritten", (t) => {
  const dir = project(t);
  fixTemplate(dir);
  const text = read(dir, "AGENTS.md");
  assert.doesNotMatch(text, /npm run (build|typecheck|app:install|app:run|app:stop)/);
  assert.doesNotMatch(text, /persist with `saveValues\(\)`/);
  assert.match(text, /run `busy-emulator typecheck`\./);
  assert.match(text, /generated by `busy-emulator build`/);
  assert.match(text, /Run `busy-emulator typecheck` and `busy-emulator build`, then check:/);
  assert.match(text, /it returns `null` only when the app has no settings file or the BUSY Bar did not answer\. An app cannot save its settings\. Do not put secrets/);
  assert.doesNotMatch(read(dir, "README.md"), /returns `null` when nothing is stored yet/);
});

test("a project without a typecheck script: the section does not name typecheck, and the template's line stays", (t) => {
  const dir = project(t, { typecheck: false });
  assert.deepEqual(fixTemplate(dir), { settings_helper: "replaced", agents_md: "added" });
  const text = read(dir, "AGENTS.md");
  const section = text.slice(text.indexOf(SECTION_BEGIN), text.indexOf(SECTION_END));
  assert.doesNotMatch(section, /typecheck/);
  assert.match(text, /run `npm run typecheck`/);
  assert.doesNotMatch(agentsSection({ typecheck: false }), /typecheck/);
  assert.match(agentsSection({ typecheck: true }), /`busy-emulator typecheck`/);
});

test("a project whose template brought no AGENTS.md gets one with the section", (t) => {
  const dir = project(t, { agents: null });
  assert.equal(writeAgentsSection(dir), "created");
  assert.match(read(dir, "AGENTS.md"), /^# AGENTS\.md\n\n<!-- busy-emulator:begin -->/);
});

test("the section: every busy-emulator call is a command with options it takes; its settings example is valid; no path of this computer", async () => {
  const commands = await loadCommands();
  const section = agentsSection();
  const calls = [...section.matchAll(/`busy-emulator ([^`]+)`/g)].map((match) => match[1]);
  assert.ok(calls.length >= 12, calls.join(" | "));
  for (const call of calls) {
    // Words as a shell splits them: a quoted value with spaces is one word, its quotes taken off.
    const words = [...call.matchAll(/'([^']*)'|"([^"]*)"|(\S+)/g)].map((m) => m[1] ?? m[2] ?? m[3]).filter((word) => !/^<.*>$/.test(word));
    const parsed = parseArguments(words, (name) => commands.find((command) => command.name === name)?.options ?? null);
    const command = commands.find((one) => one.name === parsed.name);
    assert.ok(command, `busy-emulator ${call}: no such command`);
    assert.deepEqual(parsed.unknownOptions, [], `busy-emulator ${call}`);
    assert.deepEqual(parsed.optionProblems, [], `busy-emulator ${call}`);
    assert.ok(parsed.args.length <= (command.maxArguments ?? 0), `busy-emulator ${call}: too many arguments`);
  }
  for (const name of ["dev --once", "build", "run", "logs", "screenshot", "press", "settings get", "settings set", "check", "typecheck", "trust", "create", "start", "stop", "catalog-texts set", "publish screenshots", "publish readme set", "publish prepare", "publish status", "publish signin", "publish push", "publish pr"]) assert.ok(calls.some((call) => call.startsWith(name)), name);
  const example = /```json\n(.+)\n```/.exec(section)[1];
  assert.equal(checkSettingsSchema(example).ok, true);
  // The file goes into the author's public repository: the fixed paths with ~ and %LOCALAPPDATA%, never a home.
  assert.doesNotMatch(section, /\/Users\/|\/home\/|[A-Z]:\\Users/);
  assert.ok(section.split("\n").length <= 70 && section.length <= 10000, `short: an agent reads it at every task (${section.split("\n").length} lines, ${section.length} characters)`);
});
